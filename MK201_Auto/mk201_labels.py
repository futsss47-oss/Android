"""Номер со сканера или с клавиатуры -> номер изделия для протокола и серийный номер для платы.

27.10.2026: сканируют то номер изделия (1002011002600104), то номер платы (475…2600104).
Берутся только последние 7 цифр:
  * в плату пишется «201» + 7 цифр          -> 2012600104;
  * в протокол — начало из «Настроек» + 7 цифр -> 100201100 + 2600104 = 1002011002600104."""

MODEL = "201"


class LabelError(ValueError):
    pass


def parse_label(code, prefix="100201100"):
    """-> (номер изделия для протокола, код модели '201', серийный для платы int)"""
    digits = "".join(ch for ch in str(code) if ch.isdigit())
    if len(digits) < 7:
        raise LabelError(f"В номере меньше 7 цифр: «{code}»")
    tail = digits[-7:]
    serial = int(MODEL + tail)
    return f"{prefix}{tail}", MODEL, serial
